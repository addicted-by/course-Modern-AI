#!/usr/bin/env python3
"""Synchronize the model database and generate Showcase pages from its snapshot."""
from __future__ import annotations

import argparse
import copy
from html import escape
from pathlib import Path
from urllib.parse import urljoin

from model_catalog import read_catalog, sync_catalog
from showcase_html import Node
from showcase_render import asset_base, frontmatter as shared_frontmatter, hydrate, notes_block, raw, rewrite, slide_url, source_caption, write

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "<!-- Generated by scripts/build-showcase.py from the model database. -->"
DOMAIN_NAMES = {"llm": "Language models", "t2i": "Image generation", "t2v": "Video generation", "tts": "Speech", "music": "Music"}

def page_url(record):
    return "/raw/showcase/" + record["slug"] + ".html"


def slide_html(slide, destinations):
    dom = copy.deepcopy(slide["dom"])
    dom.children = [n for n in dom.children if not isinstance(n, Node) or not n.has("fv-meta")]
    for figure in [n for n in dom.walk() if n.has("sc-evidence")]:
        picture = figure.find(tag="img")
        if picture is None:
            continue
        if figure.has("sc-evidence-strip") and picture in figure.children:
            viewport = Node("div", [("class", "showcase-diagram-scroll"), ("tabindex", "0"), ("role", "region"), ("aria-label", "Diagram; scroll horizontally to inspect details")])
            viewport.children.append(picture)
            figure.children[figure.children.index(picture)] = viewport
        link = Node("a", [("class", "showcase-figure-link"), ("href", picture.attrs["src"]), ("target", "_blank"), ("rel", "noopener")])
        link.children.append("Open full-size figure")
        figure.children.append(link)
    return rewrite(dom, destinations, slide).html()


def frontmatter(title, detail=False):
    return shared_frontmatter(title, detail, marker=GENERATED)


def source_map(model):
    rows = []
    for source in model["sources"]:
        role = "Model card" if source["role"] == "card" else "Results"
        rows.append(f'<li><span>{role}</span>{source_caption(source)}<code>{escape(source["id"])}</code></li>')
    return '<section class="showcase-source-map" id="source-slides" aria-labelledby="source-slides-title"><h2 id="source-slides-title">Source slides</h2><ul>' + "".join(rows) + '</ul></section>'


def detail_page(model, destinations):
    cards = [s for s in model["sources"] if s["role"] == "card"]
    results = [s for s in model["sources"] if s["role"] == "results"]
    primary, name, category = cards[0], model["name"], model["category"]
    content = frontmatter(name, True)
    content += raw(f'<div class="showcase-detail"><nav class="showcase-breadcrumb" aria-label="Breadcrumb"><a href="/raw/showcase.html">Model Showcase</a><span aria-hidden="true">/</span><a href="/raw/showcase.html#family-{model["family"]}">{escape(model["family_label"])}</a></nav><header class="showcase-detail-header"><p class="showcase-domain">{DOMAIN_NAMES[category]}</p><h1>{escape(name)}</h1><p>{escape(primary["title"])}</p><nav class="showcase-detail-actions" aria-label="On this page"><a href="#model-card">Model card</a><a href="#results">Results & examples</a><a href="#source-slides">Source slides</a><a href="#methods">Methods & sources</a></nav></header>' + source_map(model))
    for ident, title, sources in [("model-card", "Model card", cards), ("results", "Results & examples", results)]:
        content += raw(f'<section class="showcase-section" id="{ident}"><div class="showcase-section-heading"><h2>{title}</h2></div>')
        for source in sources:
            subtitle = f'<p class="showcase-source-subtitle">{escape(source["title"])}</p>' if ident == "results" or len(sources) > 1 else ""
            content += raw(f'<article class="showcase-slide-source" data-presentation="{escape(source["presentation_id"])}" data-slide="{escape(source["id"])}">{subtitle}<p class="showcase-slide-reference">{source_caption(source)}</p><div class="showcase-source">{slide_html(source, destinations)}</div></article>')
        content += raw('</section>')
    content += raw('<section class="showcase-section" id="methods"><div class="showcase-section-heading"><h2>Methods & sources</h2><p>Source notes, evaluation conditions and limitations from the presentation slides.</p></div>')
    for source in model["sources"]:
        role = "Model card" if source["role"] == "card" else "Results"
        content += notes_block(source, f'{role}: {source["presentation_title"]} · slide {source["position"]}')
    content += raw('</section><nav class="showcase-bottom-nav" aria-label="More models"><a href="/raw/showcase.html">Back to all models</a><a href="' + slide_url(primary) + '">View source slide</a></nav></div>')
    return content


def comparison_page(comparison, destinations):
    slide = comparison["source"]
    content = frontmatter(slide["title"], True)
    content += raw(f'<div class="showcase-detail"><nav class="showcase-breadcrumb" aria-label="Breadcrumb"><a href="/raw/showcase.html">Model Showcase</a><span aria-hidden="true">/</span><a href="/raw/showcase.html#comparisons">Comparisons</a></nav><header class="showcase-detail-header"><h1>{escape(slide["title"])}</h1><p class="showcase-slide-reference">{source_caption(slide)}</p></header><div class="showcase-source showcase-comparison">{slide_html(slide, destinations)}</div>')
    content += notes_block(slide, "Methods, sources & limitations")
    content += raw('</div>')
    return content


def model_tile(model, destinations):
    card = next(s for s in model["sources"] if s["role"] == "card")
    result = next(s for s in model["sources"] if s["role"] == "results")
    result_dom = result["dom"]
    stage = result_dom.find("sr-stage")
    picture = stage.find(tag="img") if stage else None
    video = stage.find(tag="video") if stage else None
    src = video.attrs.get("poster") if video else None
    if not src and picture:
        src = picture.attrs.get("src")
    brand = result_dom.find("sc-company")
    name, url = model["name"], page_url(model)
    if src:
        media = '<img src="' + escape(urljoin(asset_base(result), src)) + '" alt="' + escape(picture.attrs.get("alt", name + " example") if picture else name + " example") + '" loading="lazy">'
    else:
        logo = rewrite(copy.deepcopy(brand), destinations, result).html() if brand else escape(name)
        media = '<div class="showcase-brand">' + logo + '</div>'
    summary = model["summary"]
    company = model["company"]
    fields = ["Architecture", "Data", "Training", "Inference", "Voice control" if model["category"] == "tts" else "Tools"]
    status_names = {"k": "Known", "p": "Partial", "n": "Undisclosed"}
    disclosure = "".join(f'<span data-status="{s}" title="{label}: {status_names[s]}"><i aria-hidden="true"></i><span>{label}</span><span class="showcase-status-text">{status_names[s]}</span></span>' for label, s in zip(fields, model["statuses"]))
    weight = "Open weights" if model["open"] else "Hosted / API"
    search = escape(" ".join((name, company, model["family_label"], DOMAIN_NAMES[model["category"]], summary)), quote=True)
    return f'<article class="showcase-model" data-family="{model["family"]}" data-category="{model["category"]}" data-open="{str(model["open"]).lower()}" data-search="{search}"><a class="showcase-preview" href="{url}" aria-label="{escape(name)} model card">{media}</a><div class="showcase-card-body"><div class="showcase-card-meta"><span>{DOMAIN_NAMES[model["category"]]}</span><span class="showcase-weight">{weight}</span></div><h3 class="model-name"><a href="{url}">{escape(name)}</a></h3><p class="showcase-description">{escape(summary)}</p><div class="showcase-disclosure" aria-label="Public disclosure">{disclosure}</div></div><nav class="showcase-card-actions" aria-label="{escape(name)} materials"><a href="{url}">Model card</a><a href="{url}#results">Results & examples</a></nav></article>'


def family_catalog(families, models, destinations):
    by_id = {model["id"]: model for model in models}
    sections = []
    for family in families:
        ident, label = family["id"], escape(family["label"])
        members = [by_id[i] for i in family["models"]]
        count = len(members)
        title = f'{count} model' + ("s" if count != 1 else "")
        cards = "\n".join(model_tile(m, destinations) for m in members)
        sections.append(f'<section class="showcase-family" id="family-{ident}" data-family="{ident}" aria-labelledby="family-{ident}-title"><header class="showcase-family-heading"><h2 id="family-{ident}-title">{label}</h2><span class="showcase-family-count">{title}</span></header><div class="showcase-grid">{cards}</div></section>')
    return '<div class="showcase-families">' + "\n".join(sections) + '</div>'


def presentation_list(presentations):
    links = "".join(f'<li><a href="/{escape(p["html_path"])}">{escape(p["title"])}</a><span>{escape(p["module"])}</span></li>' for p in presentations)
    return '<section class="showcase-presentations" id="presentations"><h2>Source presentations</h2><ul>' + links + '</ul></section>'


def build_from_database(database, root=ROOT):
    """Render a complete snapshot without reading presentation files."""
    root = Path(root).resolve()
    database = Path(database)
    if not database.is_absolute():
        database = root / database
    catalog = read_catalog(database)
    models = catalog["models"]
    families = [family for family in catalog["families"] if family["models"]]
    comparisons = catalog["comparisons"]
    destinations = {}
    ambiguous = set()

    def bind(source, url):
        key = (source["presentation_id"], source["id"])
        if key in destinations and destinations[key] != url:
            ambiguous.add(key)
        destinations[key] = url

    for model in models:
        model["sources"] = [hydrate(source) for source in model["sources"]]
        for source in model["sources"]:
            bind(source, page_url(model) + ("#results" if source["role"] == "results" else ""))
    for comparison in comparisons:
        comparison["source"] = hydrate(comparison["source"])
        bind(comparison["source"], page_url(comparison))
    for key in ambiguous:
        del destinations[key]  # Shared slides link to the original presentation.
    groups = [(category, [(c["id"], c["label"]) for c in comparisons if c["category"] == category]) for category in DOMAIN_NAMES]
    groups = [(category, entries) for category, entries in groups if entries]
    comparison_by_id = {c["id"]: c for c in comparisons}
    pages = {root / 'raw/showcase' / (model['slug'] + '.qmd'): detail_page(model, destinations) for model in models}
    pages.update({root / 'raw/showcase' / (c['slug'] + '.qmd'): comparison_page(c, destinations) for c in comparisons})
    presentations = catalog["presentations"]
    primary_url = '/' + presentations[0]['html_path'] if len(presentations) == 1 else '#presentations'
    primary_label = 'Open the lecture' if len(presentations) == 1 else 'Source presentations'
    module_label = ' / '.join(dict.fromkeys(p['module'] for p in presentations))
    buttons = '<button type="button" data-filter="all" aria-pressed="true">All models <span>' + str(len(models)) + '</span></button>'
    for key, label in DOMAIN_NAMES.items():
        count = sum(m["category"] == key for m in models)
        buttons += f'<button type="button" data-filter="{key}" aria-pressed="false">{label} <span>{count}</span></button>'
    family_select = '<label class="showcase-family-label" for="showcase-family">Model family<select id="showcase-family"><option value="all">All families</option>' + "".join(f'<option value="{f["id"]}">{escape(f["label"])} ({len(f["models"])})</option>' for f in families) + '</select></label>'
    content = frontmatter("Model Showcase")
    content += raw(f'<div class="showcase-catalog"><header class="showcase-hero"><div><p class="showcase-domain">{escape(module_label)}</p><h1>Model Showcase</h1><p class="showcase-intro">Explore the models. Inspect the evidence.</p><p>Model families, their versions and published results across language, images, video, speech and music.</p></div><div class="showcase-hero-actions"><a class="course-button" href="{primary_url}">{primary_label}</a><a href="#comparisons">Compare models</a></div></header><p class="showcase-snapshot">{len(models)} models · {len(families)} families · 5 domains · Sources and audit dates are documented on each card.</p><div class="showcase-controls"><label class="showcase-search-label" for="showcase-search">Find a model<input id="showcase-search" type="search" placeholder="Model, family or capability" autocomplete="off"></label>{family_select}<label class="showcase-weights-label"><input id="showcase-open-weights" type="checkbox"> Open weights</label><div class="showcase-filters" role="group" aria-label="Model domain">{buttons}</div></div><div class="showcase-catalog-meta"><p id="showcase-count" role="status" aria-live="polite">{len(models)} models</p><p class="showcase-legend"><span data-status="k">Known</span><span data-status="p">Partial</span><span data-status="n">Undisclosed</span><span>Public disclosure</span></p></div><div id="showcase-empty" hidden><h2>No matching models</h2><p>Try another name or clear the filters.</p><button type="button" id="showcase-reset">Clear filters</button></div>' + family_catalog(families, models, destinations) + '<section class="showcase-comparisons" id="comparisons"><h2>Compare models</h2><p>Read the conditions alongside each comparison: prices, scores and limits describe different snapshots and evaluation setups.</p><div class="showcase-comparison-grid">' + "".join('<section><h3>' + DOMAIN_NAMES[key] + '</h3><ul>' + "".join('<li><a href="' + page_url(comparison_by_id[ident]) + '">' + escape(label) + '</a></li>' for ident, label in group) + '</ul></section>' for key, group in groups) + '</div></section>' + presentation_list(catalog["presentations"]) + '<p class="showcase-provenance">Examples and reported measurements are reproduced from the lecture’s cited sources. Each model page retains the original provenance, limitations and evaluation notes.</p></div><script src="/assets/showcase.js" defer></script>')
    pages[root / 'raw/showcase.qmd'] = content
    output = root / 'raw/showcase'
    output.mkdir(parents=True, exist_ok=True)
    # Only remove pages carrying this generator's ownership marker.
    for stale in output.glob('*.qmd'):
        if stale not in pages and GENERATED in stale.read_text()[:512]:
            stale.unlink()
            published = root / '_site/raw/showcase' / (stale.stem + '.html')
            if published.is_file():
                published.unlink()
    for path, content in pages.items():
        write(path, content)
    return {"models": len(models), "families": len(families), "comparisons": len(comparisons), "pages": len(pages)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--database', type=Path)
    parser.add_argument('--no-sync', action='store_true', help='Build only from the existing database snapshot.')
    args = parser.parse_args()
    root = args.root.resolve()
    database = args.database or Path('data/models.sqlite3')
    if not database.is_absolute():
        database = root / database
    if not args.no_sync:
        sync_catalog(root, database=database)
    stats = build_from_database(database, root)
    print(f'Showcase from SQLite: {stats["models"]} models, {stats["families"]} families, {stats["comparisons"]} comparisons.')


if __name__ == "__main__":
    main()
