#!/usr/bin/env python3
"""Synchronize the tools database and generate the Tools Showcase pages."""
from __future__ import annotations

import argparse
import copy
from html import escape
from pathlib import Path
from urllib.parse import urljoin

from showcase_html import Node
from showcase_render import asset_base, frontmatter as shared_frontmatter, hydrate, notes_block, raw, rewrite, slide_url, source_caption, write
from tool_catalog import read_catalog, sync_catalog

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "<!-- Generated by scripts/build-tools-showcase.py from the tools database. -->"
ROLE_LABELS = {"card": "Tool card", "results": "Use cases & results", "evidence": "Technical figures"}
ROLE_ANCHORS = {"card": "tool-card", "results": "use-cases", "evidence": "technical-figures"}


def page_url(tool):
    return "/raw/tools-showcase/" + tool["slug"] + ".html"


def frontmatter(title, detail=False):
    return shared_frontmatter(title, detail, css=["styles/course-showcase.css", "styles/course-tools-showcase.css"], marker=GENERATED)


def slide_html(slide, destinations):
    dom = copy.deepcopy(slide["dom"])
    # The lecture-wide Reveal navigation is replaced by the website's own navigation.
    dom.children = [n for n in dom.children if not isinstance(n, Node) or not n.has("ts-meta")]
    rewrite(dom, destinations, slide)
    for figure in [n for n in dom.walk() if n.has("ts-evidence-figure")]:
        image = figure.find(tag="img")
        if image is None:
            continue
        link = Node("a", [("class", "showcase-figure-link"), ("href", image.attrs["src"]), ("target", "_blank"), ("rel", "noopener")])
        link.children.append("Open full-size figure")
        figure.children.append(link)
    return dom.html()


def source_map(tool):
    rows = []
    for source in tool["sources"]:
        role = ROLE_LABELS[source["role"]]
        rows.append(f'<li><span>{role}</span>{source_caption(source)}<code>{escape(source["id"])}</code></li>')
    return '<section class="showcase-source-map" id="source-slides" aria-labelledby="source-slides-title"><h2 id="source-slides-title">Source slides</h2><ul>' + "".join(rows) + "</ul></section>"


def detail_page(tool, destinations):
    name = tool["name"]
    primary = next(source for source in tool["sources"] if source["role"] == "card")
    page = frontmatter(name, True)
    group_url = "/raw/tools-showcase.html#family-" + escape(tool["group_id"])
    role_links = "".join(f'<a href="#{ROLE_ANCHORS[role]}">{ROLE_LABELS[role]}</a>' for role in ("card", "results", "evidence") if any(source["role"] == role for source in tool["sources"]))
    page += raw(f'<div class="showcase-detail tools-showcase-detail"><nav class="showcase-breadcrumb" aria-label="Breadcrumb"><a href="/raw/tools-showcase.html">Tools Showcase</a><span aria-hidden="true">/</span><a href="{group_url}">{escape(tool["group_label"])}</a></nav><header class="showcase-detail-header"><p class="showcase-domain">{escape(tool["group_label"])} · {escape(tool["surface"])}</p><h1>{escape(name)}</h1><p>{escape(tool["summary"])}</p><nav class="showcase-detail-actions" aria-label="On this page">{role_links}<a href="#source-slides">Source slides</a><a href="#methods">Methods & sources</a></nav></header>' + source_map(tool))
    for role in ("card", "results", "evidence"):
        sources = [source for source in tool["sources"] if source["role"] == role]
        if not sources:
            continue
        ident, title = ROLE_ANCHORS[role], ROLE_LABELS[role]
        page += raw(f'<section class="showcase-section" id="{ident}"><div class="showcase-section-heading"><h2>{title}</h2></div>')
        for source in sources:
            subtitle = f'<p class="showcase-source-subtitle">{escape(source["title"])}</p>' if role != "card" or len(sources) > 1 else ""
            page += raw(f'<article class="showcase-slide-source" data-presentation="{escape(source["presentation_id"])}" data-slide="{escape(source["id"])}">{subtitle}<p class="showcase-slide-reference">{source_caption(source)}</p><div class="showcase-source tools-showcase-source ts-{escape(tool["slug"])}">{slide_html(source, destinations)}</div></article>')
        page += raw("</section>")
    page += raw('<section class="showcase-section" id="methods"><div class="showcase-section-heading"><h2>Methods & sources</h2><p>Original slide notes, source links and reported conditions for the material above.</p></div>')
    for source in tool["sources"]:
        page += notes_block(source, f'{ROLE_LABELS[source["role"]]}: {source["presentation_title"]} · slide {source["position"]}')
    page += raw('</section><nav class="showcase-bottom-nav" aria-label="More tools"><a href="/raw/tools-showcase.html">Back to all tools</a><a href="' + slide_url(primary) + '">View source slide</a></nav></div>')
    return page


def tool_tile(tool):
    primary = next(source for source in tool["sources"] if source["role"] == "card")
    url = page_url(tool)
    logo_src = tool.get("logo_src")
    if logo_src:
        logo = f'<img src="{escape(urljoin(asset_base(primary), logo_src))}" alt="{escape(tool.get("logo_alt") or tool["name"])}" loading="lazy">'
    else:
        logo = escape(tool["name"])
    search = escape(" ".join((tool["name"], tool["group_label"], tool["surface"], tool["summary"])), quote=True)
    return f'<article class="showcase-model tools-showcase-tool" data-family="{escape(tool["group_id"])}" data-category="{escape(tool["group_id"])}" data-search="{search}"><a class="showcase-preview" href="{url}" aria-label="{escape(tool["name"])} tool card"><span class="showcase-brand">{logo}</span></a><div class="showcase-card-body"><div class="showcase-card-meta"><span>{escape(tool["group_label"])}</span><span>{escape(tool["surface"])}</span></div><h3 class="model-name"><a href="{url}">{escape(tool["name"])}</a></h3><p class="showcase-description">{escape(tool["summary"])}</p></div><nav class="showcase-card-actions" aria-label="{escape(tool["name"])} materials"><a href="{url}">Tool card</a><a href="{url}#use-cases">Use cases & results</a></nav></article>'


def group_catalog(groups, tools):
    by_id = {tool["id"]: tool for tool in tools}
    sections = []
    for group in groups:
        members = [by_id[ident] for ident in group["tools"] if ident in by_id]
        if not members:
            continue
        ident, label = escape(group["id"]), escape(group["label"])
        cards = "\n".join(tool_tile(tool) for tool in members)
        sections.append(f'<section class="showcase-family" id="family-{ident}" data-family="{ident}" aria-labelledby="family-{ident}-title"><header class="showcase-family-heading"><h2 id="family-{ident}-title">{label}</h2><span class="showcase-family-count">{len(members)} tools</span></header><div class="showcase-grid">{cards}</div></section>')
    return '<div class="showcase-families">' + "\n".join(sections) + "</div>"


def build_from_database(database, root=ROOT):
    """Render from the database snapshot without reading presentation files."""
    root = Path(root).resolve()
    database = Path(database)
    if not database.is_absolute():
        database = root / database
    catalog = read_catalog(database)
    tools = catalog["tools"]
    groups = [group for group in catalog["groups"] if group["tools"]]
    destinations = {}
    ambiguous = set()
    for tool in tools:
        tool["sources"] = [hydrate(source) for source in tool["sources"]]
        for source in tool["sources"]:
            key = (source["presentation_id"], source["id"])
            url = page_url(tool) + "#" + ROLE_ANCHORS[source["role"]]
            if key in destinations and destinations[key] != url:
                ambiguous.add(key)
            destinations[key] = url
    for key in ambiguous:
        del destinations[key]
    pages = {root / "raw/tools-showcase" / (tool["slug"] + ".qmd"): detail_page(tool, destinations) for tool in tools}
    presentations = catalog["presentations"]
    primary_url = "/" + presentations[0]["html_path"] if len(presentations) == 1 else "#presentations"
    primary_label = "Open the lecture" if len(presentations) == 1 else "Source presentations"
    buttons = f'<button type="button" data-filter="all" aria-pressed="true">All tools <span>{len(tools)}</span></button>'
    for group in groups:
        count = sum(tool["group_id"] == group["id"] for tool in tools)
        buttons += f'<button type="button" data-filter="{escape(group["id"])}" aria-pressed="false">{escape(group["label"])} <span>{count}</span></button>'
    page = frontmatter("Tools Showcase")
    page += raw(f'<div class="showcase-catalog tools-showcase-catalog" data-noun="tool" data-group-noun="group"><header class="showcase-hero"><div><p class="showcase-domain">AI coding tools</p><h1>Tools Showcase</h1><p class="showcase-intro">Explore how the tools work. Inspect their uses and evidence.</p><p>Tool cards, published examples and technical figures from the lecture.</p></div><div class="showcase-hero-actions"><a class="course-button" href="{primary_url}">{primary_label}</a></div></header><p class="showcase-snapshot">{len(tools)} tools · {len(groups)} groups · Every detail page links to its source slides and notes.</p><div class="showcase-controls"><label class="showcase-search-label" for="showcase-search">Find a tool<input id="showcase-search" type="search" placeholder="Tool, surface or capability" autocomplete="off"></label><div class="showcase-filters" role="group" aria-label="Tool group">{buttons}</div></div><div class="showcase-catalog-meta"><p id="showcase-count" role="status" aria-live="polite">{len(tools)} tools</p></div><div id="showcase-empty" hidden><h2>No matching tools</h2><p>Try another name or clear the filter.</p><button type="button" id="showcase-reset">Clear filters</button></div>' + group_catalog(groups, tools))
    links = "".join(f'<li><a href="/{escape(p["html_path"])}">{escape(p["title"])}</a><span>{escape(p["module"])}</span></li>' for p in presentations)
    page += raw('<section class="showcase-presentations" id="presentations"><h2>Source presentations</h2><ul>' + links + '</ul></section><p class="showcase-provenance">Examples and reported results retain the lecture’s source links, conditions and limitations on each tool page.</p></div><script src="/assets/showcase.js" defer></script>')
    pages[root / "raw/tools-showcase.qmd"] = page
    output = root / "raw/tools-showcase"
    output.mkdir(parents=True, exist_ok=True)
    for stale in output.glob("*.qmd"):
        if stale not in pages and GENERATED in stale.read_text()[:512]:
            stale.unlink()
            published = root / "_site/raw/tools-showcase" / (stale.stem + ".html")
            if published.is_file():
                published.unlink()
    for path, content in pages.items():
        write(path, content)
    return {"tools": len(tools), "groups": len(groups), "pages": len(pages)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--database", type=Path)
    parser.add_argument("--no-sync", action="store_true", help="Build only from the existing database snapshot.")
    args = parser.parse_args()
    root = args.root.resolve()
    database = args.database or Path("data/tools.sqlite3")
    if not database.is_absolute():
        database = root / database
    if not args.no_sync:
        sync_catalog(root, database=database)
    stats = build_from_database(database, root)
    print(f'Tools Showcase from SQLite: {stats["tools"]} tools, {stats["groups"]} groups.')


if __name__ == "__main__":
    main()
